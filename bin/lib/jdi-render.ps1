# jdi-render.ps1 - regenerate the single-file views from the per-entry dirs
# (conflict-free layout v3). PowerShell mirror of jdi-render.sh - the rendered
# views MUST be byte-identical across both (LF endings, ordinal sort, CRLF in
# entry files normalized to LF on read).
#
# Usage:
#   jdi-render.ps1 [-Check] [-Quiet]
#
# See jdi-render.sh for the full contract. Summary:
#   .jdi/roadmap/<slug>.md   -> .jdi/ROADMAP.md   (_header + ranked phases + _footer)
#   .jdi/decisions/D-*.md    -> .jdi/DECISIONS.md (LEGACY.md + entries, ordinal sort)
#   .jdi/todos/*.md          -> .jdi/todos.md
#   .jdi/registry/R-*.md     -> .jdi/registry.md, specialists.md, reviewers.md,
#                               skills-registry.md (fenced <!-- jdi:NAME --> sections)
#
# A view is only (over)written when absent OR first line == GENERATED banner.
# -Check renders to memory and diffs instead of writing (exit 1 on drift).

[CmdletBinding()]
param(
  [switch]$Check,
  [switch]$Quiet
)

$ErrorActionPreference = 'Stop'

$BANNER = '<!-- GENERATED by jdi-cli render -- do not edit. This view is untracked; edit the per-entry files under .jdi/ and re-run: npx -y jdi-cli render -->'

$script:Warnings = 0
$script:Drift = 0

function Say([string]$msg) { if (-not $Quiet) { Write-Output $msg } }
function Warn([string]$msg) {
  if (-not $Quiet) { [Console]::Error.WriteLine($msg) }
  $script:Warnings++
}

if (-not (Test-Path .jdi -PathType Container)) { exit 0 }

# Read a file as LF-normalized text with exactly one trailing newline.
function Get-NormalizedText([string]$path) {
  $raw = [System.IO.File]::ReadAllText($path)
  $raw = $raw -replace "`r`n", "`n" -replace "`r", "`n"
  if (-not $raw.EndsWith("`n")) { $raw += "`n" }
  return $raw
}

function Get-NormalizedLines([string]$path) {
  return (Get-NormalizedText $path).TrimEnd("`n") -split "`n"
}

# Entry files of a dir: *.md, skipping LEGACY* and _*, ordinal-sorted.
function Get-Entries([string]$dir) {
  $names = @(Get-ChildItem $dir -File -Filter '*.md' -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -notmatch '^(LEGACY|_)' } |
    ForEach-Object { $_.Name })
  [Array]::Sort($names, [System.StringComparer]::Ordinal)
  return $names
}

# Fenced section body of a registry entry file.
function Get-Section([string]$path, [string]$name) {
  $s = "<!-- jdi:$name -->"
  $e = "<!-- /jdi:$name -->"
  $out = New-Object System.Collections.Generic.List[string]
  $in = $false
  foreach ($line in (Get-NormalizedLines $path)) {
    if ($line -eq $s) { $in = $true; continue }
    if ($line -eq $e) { $in = $false }
    if ($in) { $out.Add($line) }
  }
  return $out
}

# Frontmatter field of the first --- block.
function Get-FmField([string]$path, [string]$key) {
  $inFm = $false
  foreach ($line in (Get-NormalizedLines $path)) {
    if (-not $inFm) {
      if ($line -eq '---') { $inFm = $true; continue } else { return '' }
    }
    if ($line -eq '---') { return '' }
    if ($line.StartsWith("$($key):")) {
      return ($line.Substring($key.Length + 1)).TrimStart()
    }
  }
  return ''
}

# Lines after the first frontmatter block. No leading '---' -> all lines;
# unterminated frontmatter -> nothing (matches the .sh awk).
function Remove-FrontMatter([string[]]$lines) {
  if ($lines.Count -eq 0 -or $lines[0] -ne '---') { return ,$lines }
  for ($i = 1; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -ne '---') { continue }
    if ($i + 1 -ge $lines.Count) { return ,@() }
    return ,($lines[($i + 1)..($lines.Count - 1)])
  }
  return ,@()
}

function Select-TrimmedLines([string[]]$lines) {
  $start = 0
  while ($start -lt $lines.Count -and $lines[$start] -eq '') { $start++ }
  $end = $lines.Count - 1
  while ($end -ge $start -and $lines[$end] -eq '') { $end-- }
  if ($end -lt $start) { return ,@() }
  return ,($lines[$start..$end])
}

# Body after the frontmatter block, leading/trailing blank lines trimmed.
function Get-Body([string]$path) {
  return Select-TrimmedLines (Remove-FrontMatter (Get-NormalizedLines $path))
}

# Install a rendered view (content = full text WITH trailing newline).
function Install-View([string]$content, [string]$target) {
  # Views are LF-only, byte-identical with the .sh renderer. Herestring
  # literals inherit this FILE's own line endings - and git checks .ps1 out
  # as CRLF (repo .gitattributes eol=crlf) - so normalize the assembled
  # content as a whole instead of trusting any single source.
  $content = $content -replace "`r`n", "`n" -replace "`r", "`n"
  if ($Check) {
    if (-not (Test-Path $target)) {
      Say "[drift] $target missing - run: npx -y jdi-cli render"
      $script:Drift++
    }
    else {
      $existing = [System.IO.File]::ReadAllText($target)
      if ($existing -ne $content) {
        Say "[drift] $target stale - run: npx -y jdi-cli render"
        $script:Drift++
      }
      else {
        Say "[ok] $target"
      }
    }
    return
  }
  if (Test-Path $target) {
    $first = (Get-NormalizedLines $target) | Select-Object -First 1
    if ($first -ne $BANNER) {
      Say "[skip] $target exists without the GENERATED banner - legacy file untouched (run migrate-layout first)"
      $script:Warnings++
      return
    }
  }
  $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
  [System.IO.File]::WriteAllText($target, $content, $utf8NoBom)
  Say "[render] $target"
}

# --- ROADMAP.md <- .jdi/roadmap/ -----------------------------------------

# Parsed `order:` of a roadmap entry; 999999 + warn when missing/unparsable.
function Get-EntryOrder([string]$path) {
  $orderRaw = Get-FmField $path 'order'
  if ($orderRaw -ne '') {
    $parsed = 0.0
    if ([double]::TryParse($orderRaw, [System.Globalization.NumberStyles]::Float,
        [System.Globalization.CultureInfo]::InvariantCulture, [ref]$parsed)) {
      return $parsed
    }
  }
  Warn "[warn] $path has no 'order:' frontmatter - sorted last"
  return [double]999999
}

# Roadmap entries as (Order, Slug, Name), sorted by (order asc, slug ordinal
# asc). Explicit comparison sort: PS 5.1 Sort-Object is neither guaranteed
# stable nor ordinal on strings; the .sh side is LC_ALL=C (ordinal).
function Get-RoadmapItems([string]$dir) {
  $items = @()
  foreach ($f in (Get-Entries $dir)) {
    $slug = $f -replace '\.md$', ''
    $order = Get-EntryOrder "$dir/$f"
    $name = Get-FmField "$dir/$f" 'name'
    if ($name -eq '') { $name = $slug }
    $items += [PSCustomObject]@{ Order = $order; Slug = $slug; Name = $name }
  }
  [Array]::Sort($items, [System.Comparison[object]]{
    param($a, $b)
    $c = $a.Order.CompareTo($b.Order)
    if ($c -ne 0) { return $c }
    return [string]::CompareOrdinal($a.Slug, $b.Slug)
  })
  return ,$items
}

# Emit one ranked phase block; warns when the body's Slug field disagrees
# with the filename (filename wins).
function Add-PhaseBlock([System.Text.StringBuilder]$sb, [int]$rank, $it, [string]$dir) {
  [void]$sb.Append("`n### Phase $($rank): $($it.Name)`n")
  foreach ($line in (Get-Body "$dir/$($it.Slug).md")) {
    [void]$sb.Append($line + "`n")
    if ($line -match '^- \*\*Slug:\*\*\s*(.*)$') {
      $declared = $Matches[1].Trim()
      if ($declared -ne '' -and $declared -ne $it.Slug) {
        Warn "[warn] $dir/$($it.Slug).md declares Slug '$declared' (filename wins)"
      }
    }
  }
}

function Render-Roadmap {
  $dir = '.jdi/roadmap'
  if (-not (Test-Path $dir -PathType Container)) { return }

  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append($BANNER + "`n`n")
  if (Test-Path "$dir/_header.md") {
    [void]$sb.Append((Get-NormalizedText "$dir/_header.md"))
  }
  else {
    [void]$sb.Append("# Roadmap`n`n## Phases`n")
  }

  $rank = 0
  $prevOrder = $null
  foreach ($it in (Get-RoadmapItems $dir)) {
    $rank++
    if ($null -ne $prevOrder -and $it.Order -eq $prevOrder) {
      Warn "[warn] duplicate order '$($it.Order)' in $dir/ (concurrent add) - stable slug tie-break applied; renumber when convenient"
    }
    $prevOrder = $it.Order
    Add-PhaseBlock $sb $rank $it $dir
  }

  if (Test-Path "$dir/_footer.md") {
    [void]$sb.Append("`n")
    [void]$sb.Append((Get-NormalizedText "$dir/_footer.md"))
  }

  Install-View $sb.ToString() '.jdi/ROADMAP.md'
}

# --- concat views (DECISIONS.md, todos.md) --------------------------------

function Render-Concat([string]$dir, [string]$target, [string]$fallbackHeader) {
  if (-not (Test-Path $dir -PathType Container)) { return }

  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append($BANNER + "`n`n")
  if (Test-Path "$dir/LEGACY.md") {
    [void]$sb.Append((Get-NormalizedText "$dir/LEGACY.md"))
  }
  else {
    [void]$sb.Append($fallbackHeader + "`n")
  }
  foreach ($f in (Get-Entries $dir)) {
    [void]$sb.Append("`n")
    [void]$sb.Append((Get-NormalizedText "$dir/$f"))
  }

  Install-View $sb.ToString() $target
}

# --- registry-group views <- .jdi/registry/ -------------------------------

# $sep 'blank' separates blocks with an empty line (registry.md); 'row'
# appends contiguously so markdown table rows stay attached to the header.
function Render-RegistryView([string]$section, [string]$legacy, [string]$target, [string]$sep, [string]$fallbackHeader) {
  $dir = '.jdi/registry'

  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append($BANNER + "`n`n")
  if (Test-Path "$dir/$legacy") {
    [void]$sb.Append((Get-NormalizedText "$dir/$legacy"))
  }
  else {
    [void]$sb.Append($fallbackHeader + "`n")
  }
  foreach ($f in (Get-Entries $dir)) {
    $body = Get-Section "$dir/$f" $section
    if ($body.Count -eq 0) { continue }
    if ($sep -eq 'blank') { [void]$sb.Append("`n") }
    foreach ($line in $body) { [void]$sb.Append($line + "`n") }
  }

  Install-View $sb.ToString() $target
}

function Render-RegistryGroup {
  if (-not (Test-Path .jdi/registry -PathType Container)) { return }

  Render-RegistryView 'registry' 'LEGACY.md' '.jdi/registry.md' 'blank' @'
# Registry

Audit trail of every specialist/agent created for this project.
'@.TrimEnd("`r", "`n")

  Render-RegistryView 'specialists' 'LEGACY-specialists.md' '.jdi/specialists.md' 'row' @'
# Specialists

| Stack | Agent | File glob | Trigger |
|---|---|---|---|
'@.TrimEnd("`r", "`n")

  Render-RegistryView 'reviewers' 'LEGACY-reviewers.md' '.jdi/reviewers.md' 'row' @'
# Reviewers

| Agent | File glob | Trigger | Blocks ship? |
|---|---|---|---|
'@.TrimEnd("`r", "`n")

  Render-RegistryView 'skills' 'LEGACY-skills.md' '.jdi/skills-registry.md' 'row' @'
# Skills Registry

| Skill | Path | Quando aplicar | Loaded by |
|---|---|---|---|
'@.TrimEnd("`r", "`n")
}

# --- run ------------------------------------------------------------------

Render-Roadmap
Render-Concat '.jdi/decisions' '.jdi/DECISIONS.md' '# Locked project decisions'
Render-Concat '.jdi/todos' '.jdi/todos.md' '# Todos'
Render-RegistryGroup

if ($Check) {
  if ($script:Drift -gt 0 -or $script:Warnings -gt 0) {
    Say "render --check: FAIL ($($script:Drift) drift, $($script:Warnings) warning(s))"
    exit 1
  }
  Say 'render --check: PASS'
}
exit 0
