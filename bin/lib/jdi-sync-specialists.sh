#!/usr/bin/env bash
# jdi-sync-specialists.sh — materialize the per-project specialists
# (.jdi/agents/jdi-*.md, canonical JDI frontmatter) into the runtime agent
# dirs where each runtime actually discovers them:
#   claude      .claude/agents/<n>.md
#   copilot     .github/agents/<n>.agent.md
#   opencode    .opencode/agents/<n>.md
#   antigravity .agents/skills/<n>/SKILL.md
#   junie       .junie/agents/<n>.md
#
# Why: /jdi-bootstrap writes the specialists to .jdi/agents/ (source of
# truth, committed) but Claude Code resolves Agent(subagent_type=...) from
# .claude/agents/ only — same story for every other runtime — so without
# this step the do/verify loop died on the first spawn (issue #33). The
# frontmatter conversion is the one jdi-build applies to core/agents/
# (shared lib jdi-agent-emit.sh), so a specialist lands with exactly the
# shape its runtime expects (tools allowlist, model, permission block...).
#
# Usage:
#   jdi-sync-specialists.sh [claude|copilot|opencode|antigravity|junie|all]
#                           [--check] [--quiet] [--porcelain]
#
# Runtime selection: an explicit runtime always emits (its dir is created);
# `all` (default) emits for every runtime whose JDI core agents are
# installed — in the project dir, or in the user dir for user-scope
# installs (the specialist copy always lands in the PROJECT dir: specialists
# are project state and must never leak across projects).
#
# Output is byte-deterministic (same input -> same bytes; .sh and .ps1
# twins identical) and idempotent: a copy is rewritten only when its content
# differs. Every copy carries a GENERATED marker right after the frontmatter
# (preceded by the pt-BR IDIOMA directive when the project language is
# pt-BR — resolved from JDI_LANG, then .jdi/LANG, then the marker already
# present in the installed core commands — so `jdi install --lang pt-BR`
# and this script agree byte for byte).
#
#   --check      render in memory and compare; exit 1 on any missing/stale
#                copy (doctor + CI)
#   --quiet      no per-file output
#   --porcelain  print only the destination paths (relative, one per line)
#                of every copy written or already in sync — `git add $(...)`
#
# Exit: 0 in sync / written, 1 drift (--check), 2 usage / not a JDI project.

set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=jdi-agent-emit.sh
source "$SCRIPT_DIR/jdi-agent-emit.sh"

readonly GENERATED_PREFIX='<!-- GENERATED by jdi-cli sync-specialists from '
readonly GENERATED_SUFFIX=' -- edit the source, then re-run: npx -y jdi-cli sync-specialists -->'
readonly ALL_RUNTIMES="claude copilot opencode antigravity junie"
readonly ARCHITECT="jdi-architect"

CHECK=0
QUIET=0
PORCELAIN=0
TARGET="all"
for arg in "$@"; do
  case "$arg" in
    --check)     CHECK=1 ;;
    --quiet)     QUIET=1 ;;
    --porcelain) PORCELAIN=1; QUIET=1 ;;
    claude|copilot|opencode|antigravity|junie|all) TARGET="$arg" ;;
    *) echo "usage: jdi-sync-specialists.sh [claude|copilot|opencode|antigravity|junie|all] [--check] [--quiet] [--porcelain]" >&2; exit 2 ;;
  esac
done

say() {
  local msg="$1"
  [[ "$QUIET" -eq 1 ]] || echo "$msg"
  return 0
}

[[ -d .jdi ]] || { echo "ERROR: no .jdi/ here — run from the project root of a JDI project" >&2; exit 2; }

# Nothing to sync before /jdi-bootstrap.
if ! ls .jdi/agents/jdi-*.md >/dev/null 2>&1; then
  say "sync-specialists: no specialists in .jdi/agents/ (run /jdi-bootstrap first) — nothing to do"
  exit 0
fi

# A runtime counts as installed when its JDI core agents are present —
# project dir first, user dir second (same markers jdi-update uses).
runtime_installed() {
  local rt="$1"
  local home="${HOME:-${USERPROFILE:-}}"
  case "$rt" in
    "$RT_CLAUDE")   [[ -f ".claude/agents/$ARCHITECT.md" || -f "$home/.claude/agents/$ARCHITECT.md" ]] ;;
    "$RT_COPILOT")  [[ -f ".github/agents/$ARCHITECT.agent.md" ]] ;;
    "$RT_OPENCODE") [[ -f ".opencode/agents/$ARCHITECT.md" || -f "$home/.config/opencode/agents/$ARCHITECT.md" ]] ;;
    "$ANTIGRAVITY") [[ -d ".agents/skills/$ARCHITECT" || -d "$home/.gemini/config/skills/$ARCHITECT" ]] ;;
    "$RT_JUNIE")    [[ -f ".junie/agents/$ARCHITECT.md" || -f "$home/.junie/agents/$ARCHITECT.md" ]] ;;
    *) false ;;
  esac
  return $?
}

# Project language: explicit env (jdi.js --lang) > persisted .jdi/LANG >
# directive marker already present in installed core commands > en.
resolve_project_lang() {
  local lang="${JDI_LANG:-}"
  local probe_dir
  if [[ -z "$lang" && -f .jdi/LANG ]]; then
    lang="$(tr -d '[:space:]\357\273\277' < .jdi/LANG)"
  fi
  if [[ -z "$lang" ]]; then
    # Core command dirs only — never the specialist copies themselves, or a
    # pt-BR copy would keep re-inferring pt-BR after the project switched.
    for probe_dir in .claude/commands .github/prompts .opencode/commands .agents/skills/jdi-new .junie/skills/jdi-new; do
      if [[ -d "$probe_dir" ]] && grep -rqF "$LANG_DIRECTIVE_MARKER" "$probe_dir" 2>/dev/null; then
        lang="$LANG_PT_BR"
        break
      fi
    done
  fi
  echo "${lang:-en}"
  return 0
}

# GENERATED marker line right after the closing `---` (before the body).
add_generated_marker() {
  local name="$1"
  awk -v marker="${GENERATED_PREFIX}.jdi/agents/${name}.md${GENERATED_SUFFIX}" '
    { print }
    /^---$/ && fm < 2 { fm++; if (fm == 2) print marker }
  '
  return $?
}

# Render one (runtime, specialist) copy into <out>.
render_copy() {
  local rt="$1" src="$2" name="$3" out="$4"
  emit_agent_content "$rt" "$src" | add_generated_marker "$name" > "$out"
  if [[ "$PROJECT_LANG" == "$LANG_PT_BR" ]]; then
    inject_lang_directive_stream < "$out" > "$out.lang"
    mv "$out.lang" "$out"
  fi
  return 0
}

targets=()
if [[ "$TARGET" == "all" ]]; then
  for rt in $ALL_RUNTIMES; do
    runtime_installed "$rt" && targets+=("$rt")
  done
else
  targets=("$TARGET")
fi

if [[ ${#targets[@]} -eq 0 ]]; then
  say "sync-specialists: no JDI runtime installed here (npx jdi-cli install <runtime>) — nothing to do"
  exit 0
fi

PROJECT_LANG="$(resolve_project_lang)"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

DRIFT=0
WRITTEN=0
SAME=0

for src in .jdi/agents/jdi-*.md; do
  [[ -f "$src" ]] || continue
  name="$(basename "$src" .md)"
  # LF-normalized working copy (same basename — it becomes the agent name):
  # a CRLF checkout must render the same bytes.
  mkdir -p "$TMP_DIR/src"
  src_lf="$TMP_DIR/src/$name.md"
  tr -d '\r' < "$src" > "$src_lf"

  for rt in "${targets[@]}"; do
    dst="$(agent_dest_path "$rt" "$name")"
    out="$TMP_DIR/$rt-$name.md"
    render_copy "$rt" "$src_lf" "$name" "$out"

    if [[ -f "$dst" ]] && tr -d '\r' < "$dst" | cmp -s - "$out"; then
      SAME=$((SAME + 1))
      [[ "$PORCELAIN" -eq 1 ]] && echo "$dst"
      continue
    fi

    if [[ "$CHECK" -eq 1 ]]; then
      DRIFT=$((DRIFT + 1))
      if [[ -f "$dst" ]]; then
        say "STALE   $dst (differs from .jdi/agents/$name.md)"
      else
        say "MISSING $dst"
      fi
    else
      mkdir -p "$(dirname "$dst")"
      cp "$out" "$dst"
      WRITTEN=$((WRITTEN + 1))
      if [[ "$PORCELAIN" -eq 1 ]]; then echo "$dst"; else say "  $dst"; fi
    fi
  done
done

if [[ "$CHECK" -eq 1 ]]; then
  if [[ "$DRIFT" -gt 0 ]]; then
    say "sync-specialists: $DRIFT runtime copy(ies) missing or stale — run: npx -y jdi-cli sync-specialists"
    exit 1
  fi
  say "sync-specialists: $SAME runtime copy(ies) in sync (${targets[*]})"
  exit 0
fi

say "sync-specialists: $WRITTEN written, $SAME already in sync (${targets[*]}; lang=$PROJECT_LANG)"
exit 0
