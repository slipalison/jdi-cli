# jdi-sync-specialists.ps1 - materialize the per-project specialists
# (.jdi/agents/jdi-*.md, canonical JDI frontmatter) into the runtime agent
# dirs where each runtime actually discovers them. PowerShell twin of
# jdi-sync-specialists.sh - the copies MUST be byte-identical across both
# (LF, UTF-8 without BOM, same GENERATED marker, same pt-BR directive).
#
#   claude      .claude/agents/<n>.md
#   copilot     .github/agents/<n>.agent.md
#   opencode    .opencode/agents/<n>.md
#   antigravity .agents/skills/<n>/SKILL.md
#   junie       .junie/agents/<n>.md
#
# Usage:
#   jdi-sync-specialists.ps1 [-Runtime claude|copilot|opencode|antigravity|junie|all]
#                            [-Check] [-Quiet] [-Porcelain]
#
# See jdi-sync-specialists.sh for the full contract (issue #33).
# Exit: 0 in sync / written, 1 drift (-Check), 2 usage / not a JDI project.

[CmdletBinding()]
param(
  [Parameter(Position = 0)]
  [ValidateSet('claude','copilot','opencode','antigravity','junie','all')]
  [string]$Runtime = 'all',

  [switch]$Check,
  [switch]$Quiet,
  [switch]$Porcelain
)

$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'jdi-agent-emit.ps1')

$GeneratedPrefix = '<!-- GENERATED by jdi-cli sync-specialists from '
$GeneratedSuffix = ' -- edit the source, then re-run: npx -y jdi-cli sync-specialists -->'
$AllRuntimes = @('claude','copilot','opencode','antigravity','junie')
$Architect = 'jdi-architect'

if ($Porcelain) { $Quiet = $true }

function Say([string]$msg) { if (-not $Quiet) { Write-Output $msg } }

if (-not (Test-Path '.jdi' -PathType Container)) {
  [Console]::Error.WriteLine('ERROR: no .jdi/ here - run from the project root of a JDI project')
  exit 2
}

$specialists = @(Get-ChildItem -Path '.jdi\agents' -Filter 'jdi-*.md' -File -ErrorAction SilentlyContinue | Sort-Object Name)
if ($specialists.Count -eq 0) {
  Say 'sync-specialists: no specialists in .jdi/agents/ (run /jdi-bootstrap first) - nothing to do'
  exit 0
}

$UserHome = if ($env:HOME) { $env:HOME } else { $env:USERPROFILE }

# A runtime counts as installed when its JDI core agents are present -
# project dir first, user dir second (same markers jdi-update uses).
function Test-RuntimeInstalled([string]$rt) {
  switch ($rt) {
    'claude'      { return ((Test-Path ".claude\agents\$Architect.md") -or (Test-Path (Join-Path $UserHome ".claude\agents\$Architect.md"))) }
    'copilot'     { return (Test-Path ".github\agents\$Architect.agent.md") }
    'opencode'    { return ((Test-Path ".opencode\agents\$Architect.md") -or (Test-Path (Join-Path $UserHome ".config\opencode\agents\$Architect.md"))) }
    'antigravity' { return ((Test-Path ".agents\skills\$Architect" -PathType Container) -or (Test-Path (Join-Path $UserHome ".gemini\config\skills\$Architect") -PathType Container)) }
    'junie'       { return ((Test-Path ".junie\agents\$Architect.md") -or (Test-Path (Join-Path $UserHome ".junie\agents\$Architect.md"))) }
  }
  return $false
}

# Project language: explicit env (jdi.js -Lang) > persisted .jdi/LANG >
# directive marker already present in installed core commands > en.
function Get-ProjectLang {
  $lang = ''
  if ($env:JDI_LANG) { $lang = $env:JDI_LANG }
  if (-not $lang -and (Test-Path '.jdi\LANG')) {
    $lang = ([System.IO.File]::ReadAllText('.jdi\LANG', [System.Text.Encoding]::UTF8)).Trim()
  }
  if (-not $lang) {
    # Core command dirs only - never the specialist copies themselves, or a
    # pt-BR copy would keep re-inferring pt-BR after the project switched.
    foreach ($pd in @('.claude\commands', '.github\prompts', '.opencode\commands', '.agents\skills\jdi-new', '.junie\skills\jdi-new')) {
      if (-not (Test-Path $pd)) { continue }
      $hit = Get-ChildItem -Path $pd -Recurse -Filter '*.md' -File -ErrorAction SilentlyContinue |
        Select-String -SimpleMatch $script:LangDirectiveMarker -Quiet |
        Select-Object -First 1
      if ($hit) { $lang = $script:LangPtBr; break }
    }
  }
  if (-not $lang) { $lang = 'en' }
  return $lang
}

# GENERATED marker line right after the closing `---` (before the body).
function Add-GeneratedMarker([string]$Text, [string]$Name) {
  $marker = "$GeneratedPrefix.jdi/agents/$Name.md$GeneratedSuffix"
  $lines = [string[]]($Text -split "`n")
  $trailing = ($lines.Length -gt 0 -and $lines[-1] -eq '')
  if ($trailing) { $lines = $lines[0..($lines.Length - 2)] }
  $fm = 0
  $out = New-Object System.Collections.Generic.List[string]
  foreach ($line in $lines) {
    $out.Add($line)
    if ($line -eq '---' -and $fm -lt 2) {
      $fm++
      if ($fm -eq 2) { $out.Add($marker) }
    }
  }
  $result = ($out -join "`n")
  if ($trailing) { $result += "`n" }
  return $result
}

# Render one (runtime, specialist) copy as LF text.
function Get-RenderedCopy([string]$rt, [string]$srcPath, [string]$name) {
  $text = Get-AgentContent -Runtime $rt -SrcPath $srcPath
  $text = Add-GeneratedMarker -Text $text -Name $name
  if ($script:ProjectLang -eq $script:LangPtBr) {
    $text = Add-LangDirectiveToText -Text $text
  }
  return $text
}

$targets = @()
if ($Runtime -eq 'all') {
  foreach ($rt in $AllRuntimes) { if (Test-RuntimeInstalled $rt) { $targets += $rt } }
} else {
  $targets = @($Runtime)
}

if ($targets.Count -eq 0) {
  Say 'sync-specialists: no JDI runtime installed here (npx jdi-cli install <runtime>) - nothing to do'
  exit 0
}

$script:ProjectLang = Get-ProjectLang

$drift = 0
$written = 0
$same = 0

foreach ($spec in $specialists) {
  $name = [System.IO.Path]::GetFileNameWithoutExtension($spec.Name)

  foreach ($rt in $targets) {
    $dst = Get-AgentDestPath -Runtime $rt -Name $name
    $rendered = Get-RenderedCopy -rt $rt -srcPath $spec.FullName -name $name

    $current = $null
    if (Test-Path $dst) {
      $current = ([System.IO.File]::ReadAllText($dst, [System.Text.Encoding]::UTF8)).Replace("`r`n", "`n")
    }

    if ($null -ne $current -and $current -ceq $rendered) {
      $same++
      if ($Porcelain) { Write-Output $dst }
      continue
    }

    if ($Check) {
      $drift++
      if ($null -ne $current) { Say "STALE   $dst (differs from .jdi/agents/$name.md)" }
      else { Say "MISSING $dst" }
    } else {
      Write-Utf8NoBom -Path (Join-Path (Get-Location).Path $dst) -Content $rendered
      $written++
      if ($Porcelain) { Write-Output $dst } else { Say "  $dst" }
    }
  }
}

if ($Check) {
  if ($drift -gt 0) {
    Say "sync-specialists: $drift runtime copy(ies) missing or stale - run: npx -y jdi-cli sync-specialists"
    exit 1
  }
  Say "sync-specialists: $same runtime copy(ies) in sync ($($targets -join ' '))"
  exit 0
}

Say "sync-specialists: $written written, $same already in sync ($($targets -join ' '); lang=$script:ProjectLang)"
exit 0
