#!/usr/bin/env bash
# jdi-render.sh — regenerate the single-file views from the per-entry dirs
# (conflict-free layout v3).
#
# Usage:
#   jdi-render.sh [--check] [--quiet]
#
# v3 layout stores every multi-writer stream as one-file-per-entry:
#   .jdi/roadmap/<slug>.md          one file per phase (order: in frontmatter)
#   .jdi/decisions/D-*.md           one file per decision (filename = ID)
#   .jdi/todos/*.md                 one file per todo batch (per phase)
#   .jdi/registry/R-*.md            one file per bootstrap/create run
#
# The old single-file paths become UNTRACKED views regenerated here, byte-
# deterministic, so every existing reader (agents, greps, humans) keeps its
# path while writers never touch a shared file. GitHub/GitLab/ADO ignore
# .gitattributes merge drivers on server-side PR merges, so conflict-freedom
# must come from the file layout, not from merge=union.
#
# Views written (only when their source dir exists):
#   .jdi/ROADMAP.md      <- .jdi/roadmap/   (_header.md + ranked phases + _footer.md)
#   .jdi/DECISIONS.md    <- .jdi/decisions/ (LEGACY.md + entries, C-sorted)
#   .jdi/todos.md        <- .jdi/todos/     (LEGACY.md + entries, C-sorted)
#   .jdi/registry.md     <- .jdi/registry/  (LEGACY.md + jdi:registry sections)
#   .jdi/specialists.md  <- .jdi/registry/  (LEGACY-specialists.md + jdi:specialists sections)
#   .jdi/reviewers.md    <- .jdi/registry/  (LEGACY-reviewers.md + jdi:reviewers sections)
#   .jdi/skills-registry.md <- .jdi/registry/ (LEGACY-skills.md + jdi:skills sections)
#
# Registry entry files carry fenced sections:
#   <!-- jdi:registry --> ... <!-- /jdi:registry -->
#   <!-- jdi:specialists --> ... <!-- /jdi:specialists -->
#   <!-- jdi:reviewers --> ... <!-- /jdi:reviewers -->
#   <!-- jdi:skills --> ... <!-- /jdi:skills -->
#
# Safety: a view is only (over)written when it is absent OR its first line is
# the GENERATED banner. A tracked legacy file without the banner is never
# clobbered — that state means "migration not run" and the dir is ignored by
# writers until `jdi-cli migrate-layout` runs.
#
# --check: render to temp and diff against the current views instead of
# writing; also reports layout warnings (duplicate order, filename/slug
# mismatch). Exit 1 when anything drifts or warns — used by doctor/CI.
#
# Exit: 0 = views written (or nothing to do), 1 = --check drift/warnings
#       (in write mode, warnings print but do not fail), 2 = usage error.

set -u

BANNER='<!-- GENERATED by jdi-cli render -- do not edit. This view is untracked; edit the per-entry files under .jdi/ and re-run: npx -y jdi-cli render -->'

CHECK=0
QUIET=0
for arg in "$@"; do
  case "$arg" in
    --check) CHECK=1 ;;
    --quiet) QUIET=1 ;;
    *) echo "usage: jdi-render.sh [--check] [--quiet]" >&2; exit 2 ;;
  esac
done

say() {
  local msg="$1"
  [[ "$QUIET" -eq 1 ]] || echo "$msg"
  return 0
}

# Not a JDI project or not migrated to v3 — nothing to render, by design.
[[ -d .jdi ]] || exit 0

WARNINGS=0
DRIFT=0
TMPDIR_R="$(mktemp -d)"
trap 'rm -rf "$TMPDIR_R"' EXIT

# cat a file normalizing CRLF -> LF and guaranteeing a trailing newline, so
# the rendered views are byte-identical regardless of who wrote the entries
# (Windows agents write CRLF; the .sh and .ps1 renderers must agree).
cat_nl() {
  local file="$1"
  awk '{ sub(/\r$/, ""); print }' "$file"
  return $?
}

# List entry files of a dir, C-sorted, skipping LEGACY*, _*, hidden, non-.md.
entries_of() {
  local dir="$1"
  ( cd "$dir" 2>/dev/null && LC_ALL=C ls -1 2>/dev/null ) \
    | LC_ALL=C sort \
    | grep -E '\.md$' \
    | grep -vE '^(LEGACY|_)' || true
  return 0
}

# Extract a fenced section from a registry entry file.
section_of() {
  local file="$1" name="$2"
  awk -v s="<!-- jdi:${name} -->" -v e="<!-- /jdi:${name} -->" \
    '{ sub(/\r$/, "") } $0 == s { f = 1; next } $0 == e { f = 0 } f' "$file"
  return $?
}

# Frontmatter field (first block between --- lines): field_of <file> <key>
field_of() {
  local file="$1" key="$2"
  awk -v key="$key" '
    { sub(/\r$/, "") }
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { exit }
    fm && index($0, key ":") == 1 {
      sub("^" key ":[[:space:]]*", ""); print; exit
    }
  ' "$file"
  return $?
}

# Body after the frontmatter block, stripped of leading blank lines.
body_of() {
  local file="$1"
  awk '
    { sub(/\r$/, "") }
    NR == 1 && $0 == "---" { fm = 1; next }
    fm == 1 { if ($0 == "---") { fm = 2; next } next }
    fm != 1 { lines[++n] = $0 }
    END {
      start = 1
      while (start <= n && lines[start] == "") start++
      end = n
      while (end >= start && lines[end] == "") end--
      for (i = start; i <= end; i++) print lines[i]
    }
  ' "$file"
  return $?
}

# Install a rendered view: absent or banner-first-line -> write; else refuse.
# In --check mode, diff instead.
install_view() {
  local tmp="$1" target="$2"
  if [[ "$CHECK" -eq 1 ]]; then
    if [[ ! -f "$target" ]]; then
      say "[drift] $target missing — run: npx -y jdi-cli render"
      DRIFT=$((DRIFT + 1))
    elif ! cmp -s "$tmp" "$target"; then
      say "[drift] $target stale — run: npx -y jdi-cli render"
      DRIFT=$((DRIFT + 1))
    else
      say "[ok] $target"
    fi
    return 0
  fi
  if [[ -f "$target" ]] && [[ "$(head -n 1 "$target")" != "$BANNER" ]]; then
    say "[skip] $target exists without the GENERATED banner — legacy file untouched (run migrate-layout first)"
    WARNINGS=$((WARNINGS + 1))
    return 0
  fi
  mv "$tmp" "$target"
  say "[render] $target"
  return 0
}

# --- ROADMAP.md <- .jdi/roadmap/ -----------------------------------------

render_roadmap() {
  local dir=".jdi/roadmap" out="$TMPDIR_R/ROADMAP.md"
  [[ -d "$dir" ]] || return 0

  {
    echo "$BANNER"
    echo ""
    if [[ -f "$dir/_header.md" ]]; then
      cat_nl "$dir/_header.md"
    else
      echo "# Roadmap"
      echo ""
      echo "## Phases"
    fi

    # rank entries by (order numeric asc, slug asc)
    local list="$TMPDIR_R/roadmap-list"
    : > "$list"
    local f slug order name
    while IFS= read -r f; do
      [[ -n "$f" ]] || continue
      slug="${f%.md}"
      order="$(field_of "$dir/$f" order)"
      name="$(field_of "$dir/$f" name)"
      if [[ -z "$order" ]]; then
        say "[warn] $dir/$f has no 'order:' frontmatter — sorted last" >&2
        WARNINGS=$((WARNINGS + 1))
        order=999999
      fi
      [[ -n "$name" ]] || name="$slug"
      printf '%s\t%s\t%s\n' "$order" "$slug" "$name" >> "$list"
    done <<EOF
$(entries_of "$dir")
EOF

    local rank=0 prev_order="" line
    while IFS=$'\t' read -r order slug name; do
      [[ -n "$slug" ]] || continue
      rank=$((rank + 1))
      if [[ -n "$prev_order" && "$order" == "$prev_order" ]]; then
        say "[warn] duplicate order '$order' in $dir/ (concurrent add) — stable slug tie-break applied; renumber when convenient" >&2
        WARNINGS=$((WARNINGS + 1))
      fi
      prev_order="$order"
      echo ""
      echo "### Phase ${rank}: ${name}"
      body_of "$dir/$slug.md"
      # filename is the slug of record — flag drift against the Slug: field
      line="$(grep -m1 -E '^- \*\*Slug:\*\*' "$dir/$slug.md" | sed -E 's/^- \*\*Slug:\*\*[[:space:]]*//' | tr -d '\r' || true)"
      if [[ -n "$line" && "$line" != "$slug" ]]; then
        say "[warn] $dir/$slug.md declares Slug '$line' (filename wins)" >&2
        WARNINGS=$((WARNINGS + 1))
      fi
    done < <(LC_ALL=C sort -t "$(printf '\t')" -k1,1g -k2,2 "$list")

    if [[ -f "$dir/_footer.md" ]]; then
      echo ""
      cat_nl "$dir/_footer.md"
    fi
  } > "$out"

  install_view "$out" ".jdi/ROADMAP.md"
  return 0
}

# --- concat views (DECISIONS.md, todos.md) --------------------------------

render_concat() {
  local dir="$1" target="$2" fallback_header="$3"
  [[ -d "$dir" ]] || return 0
  local out="$TMPDIR_R/$(basename "$target")"

  {
    echo "$BANNER"
    echo ""
    if [[ -f "$dir/LEGACY.md" ]]; then
      cat_nl "$dir/LEGACY.md"
    else
      printf '%s\n' "$fallback_header"
    fi
    local f
    while IFS= read -r f; do
      [[ -n "$f" ]] || continue
      echo ""
      cat_nl "$dir/$f"
    done <<EOF
$(entries_of "$dir")
EOF
  } > "$out"

  install_view "$out" "$target"
  return 0
}

# --- registry-group views <- .jdi/registry/ -------------------------------

# sep="blank" separates blocks with an empty line (registry.md); sep="row"
# appends contiguously so markdown table rows stay attached to the header.
render_registry_view() {
  local section="$1" legacy="$2" target="$3" sep="$4" fallback_header="$5"
  local dir=".jdi/registry" out="$TMPDIR_R/$(basename "$target")"

  {
    echo "$BANNER"
    echo ""
    if [[ -f "$dir/$legacy" ]]; then
      cat_nl "$dir/$legacy"
    else
      printf '%s\n' "$fallback_header"
    fi
    local f body
    while IFS= read -r f; do
      [[ -n "$f" ]] || continue
      body="$(section_of "$dir/$f" "$section")"
      [[ -n "$body" ]] || continue
      [[ "$sep" == "blank" ]] && echo ""
      printf '%s\n' "$body"
    done <<EOF
$(entries_of "$dir")
EOF
  } > "$out"

  install_view "$out" "$target"
  return 0
}

render_registry_group() {
  [[ -d .jdi/registry ]] || return 0

  render_registry_view "registry" "LEGACY.md" ".jdi/registry.md" "blank" \
'# Registry

Audit trail of every specialist/agent created for this project.'

  render_registry_view "specialists" "LEGACY-specialists.md" ".jdi/specialists.md" "row" \
'# Specialists

| Stack | Agent | File glob | Trigger |
|---|---|---|---|'

  render_registry_view "reviewers" "LEGACY-reviewers.md" ".jdi/reviewers.md" "row" \
'# Reviewers

| Agent | File glob | Trigger | Blocks ship? |
|---|---|---|---|'

  render_registry_view "skills" "LEGACY-skills.md" ".jdi/skills-registry.md" "row" \
'# Skills Registry

| Skill | Path | Quando aplicar | Loaded by |
|---|---|---|---|'
  return 0
}

# --- run ------------------------------------------------------------------

render_roadmap
render_concat ".jdi/decisions" ".jdi/DECISIONS.md" "# Locked project decisions"
render_concat ".jdi/todos" ".jdi/todos.md" "# Todos"
render_registry_group

if [[ "$CHECK" -eq 1 ]]; then
  if [[ "$DRIFT" -gt 0 || "$WARNINGS" -gt 0 ]]; then
    say "render --check: FAIL ($DRIFT drift, $WARNINGS warning(s))"
    exit 1
  fi
  say "render --check: PASS"
fi
exit 0
